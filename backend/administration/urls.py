    path("rooms/<int:room_id>/end/", EndRoomView.as_view()),
    path("rooms/<int:room_id>/", AdminRoomDetailView.as_view()),
    path("rooms/<int:room_id>/submissions/", AdminRoomSubmissionsView.as_view()),
    path("rooms/<int:room_id>/participants/<int:participant_id>/kick/",KickParticipantView.as_view()),
    path("submissions/", AdminAllSubmissionsView.as_view()),
    path("users/<int:user_id>/block/", BlockUserView.as_view()),
    path("users/<int:user_id>/unblock/", UnblockUserView.as_view()),
