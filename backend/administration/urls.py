    path("stats/", AdminPlatformStatsView.as_view()),
    path("platform-stats/", AdminPlatformStatsView.as_view()),
    path("challenges/", ChallengeListView.as_view()),
    path("challenges/create/", CreateChallengeView.as_view()),
